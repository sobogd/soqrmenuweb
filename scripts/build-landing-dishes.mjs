/*
 * Downloads landing-menu dish images from object storage and writes
 * 600x600 webp thumbnails to public/landing/. Run once when source
 * images change. The output is committed so the landing serves
 * tiny, locally-cached files instead of 200KB+ remote originals.
 *
 *   node scripts/build-landing-dishes.mjs
 */
import sharp from "sharp";
import { mkdirSync, existsSync } from "fs";
import { writeFile } from "fs/promises";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outDir = join(__dirname, "..", "public", "landing");
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });

const BASE = "https://nbg1.your-objectstorage.com/sobogd/temp/cmi5yzq5v0000vx0hbjmbks82/";
const SIZE = 600;
const QUALITY = 75;

const dishes = [
  { id: "steak-tartar", file: "import-steak-tartar-de-buey-1778342626492-ppf0yn.webp" },
  { id: "burrata", file: "import-burrata-con-trufa-negra-1778342648771-e2nq8b.webp" },
  { id: "tataki", file: "import-tataki-de-atun-rojo-1778342666692-bohb4o.webp" },
  { id: "chuleton", file: "import-chuleton-madurado-400g-1778342757733-rosblf.webp" },
  { id: "bacalao", file: "import-bacalao-negro-al-miso-1778342789206-wyxdgo.webp" },
  { id: "coulant", file: "import-coulant-de-chocolate-negro-1778343210436-aym6r6.webp" },
  { id: "tarta-queso", file: "import-tarta-de-queso-vasca-1778343228534-pfiitj.webp" },
  { id: "tiramisu", file: "import-tiramisu-noir-1778343259241-qy6v7k.webp" },
  { id: "crema-catalana", file: "import-crema-catalana-1778343273378-7lv8kg.webp" },
];

for (const d of dishes) {
  const url = BASE + d.file;
  const res = await fetch(url);
  if (!res.ok) {
    console.error(`fetch failed ${d.id}: ${res.status}`);
    continue;
  }
  const buf = Buffer.from(await res.arrayBuffer());
  const out = join(outDir, `${d.id}.webp`);
  await sharp(buf)
    .resize(SIZE, SIZE, { fit: "cover" })
    .webp({ quality: QUALITY })
    .toFile(out);
  const meta = await sharp(out).metadata();
  console.log(`${d.id}: ${meta.size ?? "?"}B  ${meta.width}x${meta.height}`);
}

await writeFile(
  join(outDir, "README.md"),
  "Generated by scripts/build-landing-dishes.mjs — do not edit by hand.\n"
);
console.log("done");
