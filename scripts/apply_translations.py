def set_nested(data, key_path, value):
    """Set a value in a nested dict using dot-separated key path."""
    keys = key_path.split(".")
    current = data
    for key in keys[:-1]:
        if key not in current:
            current[key] = {}
        current = current[key]
    current[keys[-1]] = value


def main():
    updated_count = 0
    for locale in LOCALES:
        filepath = os.path.join(MESSAGES_DIR, f"{locale}.json")
        if not os.path.exists(filepath):
            print(f"WARNING: {filepath} does not exist, skipping")
            continue

        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)

        keys_set = 0
        for key_path, locale_translations in TRANSLATIONS.items():
            if locale in locale_translations:
                set_nested(data, key_path, locale_translations[locale])
                keys_set += 1

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
            f.write("\n")

        print(f"Updated {locale}.json — {keys_set} keys set")
        updated_count += 1

    print(f"\nDone. Updated {updated_count} locale files with {len(TRANSLATIONS)} keys each.")


if __name__ == "__main__":
    main()
